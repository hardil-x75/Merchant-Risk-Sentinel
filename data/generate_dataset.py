"""Synthetic Dataset Generator for Merchant Risk Sentinel.

Generates realistic multi-merchant payment transaction streams with benign baseline traffic
and controlled, non-trivial fraud/risk patterns for defensive model training.

DISCLAIMER: All synthetic transaction data, customer IDs, and risk signals generated by
this script are benchmark simulations for defensive detection modeling. They do NOT represent
live Razorpay customer data or gateway telemetry.
"""

import os
import random
from datetime import datetime, timedelta, timezone
from typing import List, Dict, Any
import numpy as np
import pandas as pd


def generate_synthetic_transactions(
    num_merchants: int = 20,
    txns_per_merchant: int = 500,
    fraud_prevalence: float = 0.08,
    random_seed: int = 42,
    time_span_days: int = 30,
) -> pd.DataFrame:
    """Generate realistic chronological multi-merchant transaction dataset.

    Args:
        num_merchants: Number of distinct merchant accounts
        txns_per_merchant: Average transactions generated per merchant
        fraud_prevalence: Proportion of fraudulent/anomalous transactions (0.0 to 1.0)
        random_seed: Seed for reproducibility
        time_span_days: Total time window in days

    Returns:
        pd.DataFrame: Chronologically sorted transaction dataset with target label 'is_fraud'
    """
    np.random.seed(random_seed)
    random.seed(random_seed)

    start_time = datetime(2026, 8, 1, 0, 0, 0, tzinfo=timezone.utc)
    total_txns = num_merchants * txns_per_merchant
    num_fraud = int(total_txns * fraud_prevalence)
    num_legit = total_txns - num_fraud

    # Generate Merchant Baselines
    merchants = [f"merch_{i+1:02d}" for i in range(num_merchants)]
    merchant_profiles = {}
    for m in merchants:
        merchant_profiles[m] = {
            "avg_amount": np.random.uniform(500.0, 5000.0),
            "std_amount": np.random.uniform(100.0, 1500.0),
            "preferred_methods": np.random.choice(
                ["upi", "card", "netbanking", "wallet"],
                size=2,
                replace=False,
                p=[0.5, 0.3, 0.1, 0.1],
            ).tolist(),
        }

    # Generate Customer Pool
    num_customers = max(50, total_txns // 8)
    customers = [f"cust_{i+1:04d}" for i in range(num_customers)]
    customer_creation_ages = {
        c: np.random.uniform(1.0, 365.0) for c in customers
    }

    email_domains = ["gmail.com", "yahoo.com", "outlook.com", "hotmail.com", "icloud.com"]
    disposable_domains = ["tempmail.com", "disposable.org", "mailinator.com", "guerrillamail.com"]
    payment_methods = ["upi", "card", "netbanking", "wallet"]
    card_networks = ["visa", "mastercard", "rupay"]
    banks = ["HDFC", "ICICI", "SBI", "AXIS", "KOTAK", "PAYTM"]

    transactions: List[Dict[str, Any]] = []

    # Generate timestamps across time span
    random_offsets_sec = np.sort(
        np.random.uniform(0, time_span_days * 86400, size=total_txns)
    )

    # Label assignment: randomly pick indices to be fraud
    fraud_indices = set(
        np.random.choice(total_txns, size=num_fraud, replace=False)
    )

    txn_counter = 1

    for idx in range(total_txns):
        is_fraud = 1 if idx in fraud_indices else 0
        timestamp = start_time + timedelta(seconds=float(random_offsets_sec[idx]))

        merchant_id = random.choice(merchants)
        m_profile = merchant_profiles[merchant_id]

        if is_fraud == 0:
            # Benign Transaction Dynamics (with realistic real-world noise & feature overlap)
            customer_id = random.choice(customers)
            amount = max(
                50.0,
                np.random.normal(m_profile["avg_amount"], m_profile["std_amount"]),
            )
            # Legitimate transactions occasionally (4%) use disposable/temporary emails or non-domestic billing (10%)
            email_domain = (
                random.choice(disposable_domains)
                if random.random() < 0.04
                else random.choice(email_domains)
            )
            billing_country = "IN" if random.random() < 0.90 else random.choice(["US", "GB", "AE", "SG"])
            payment_method = (
                m_profile["preferred_methods"][0]
                if random.random() < 0.7
                else random.choice(payment_methods)
            )
            status = "captured" if random.random() < 0.95 else "failed"
            card_network = random.choice(card_networks) if payment_method == "card" else None
            bank_name = random.choice(banks)

        else:
            # Fraudulent / Anomalous Pattern Dynamics (Defensive Benchmark Scenarios)
            # Combination of signals: Velocity bursts, amount deviations, retry surges, geo/domain anomalies
            scenario = random.choice(["velocity_burst", "amount_anomaly", "retry_surge", "suspicious_geo_domain"])

            # Customer pool for fraud: 70% concentrated (velocity/bursts), 30% random
            customer_id = random.choice(customers[:25]) if random.random() < 0.70 else random.choice(customers)

            if scenario == "amount_anomaly":
                # High amount relative to merchant baseline (e.g. 4x - 10x average)
                amount = m_profile["avg_amount"] * np.random.uniform(4.0, 10.0)
                email_domain = random.choice(email_domains) if random.random() < 0.40 else random.choice(disposable_domains)
                billing_country = "IN" if random.random() < 0.60 else random.choice(["US", "GB", "AE"])
                payment_method = random.choice(payment_methods)
                status = "captured" if random.random() < 0.8 else "failed"

            elif scenario == "velocity_burst":
                # Moderate amount with high velocity burst
                amount = m_profile["avg_amount"] * np.random.uniform(1.2, 2.8)
                email_domain = random.choice(disposable_domains) if random.random() < 0.35 else random.choice(email_domains)
                billing_country = random.choice(["IN", "US", "AE", "GB"])
                payment_method = random.choice(payment_methods)
                status = "captured" if random.random() < 0.85 else "failed"

            elif scenario == "retry_surge":
                # Rapid failed attempts
                amount = m_profile["avg_amount"] * np.random.uniform(1.3, 3.5)
                email_domain = random.choice(email_domains) if random.random() < 0.60 else random.choice(disposable_domains)
                billing_country = "IN" if random.random() < 0.75 else random.choice(["US", "AE"])
                payment_method = "card"
                status = "failed" if random.random() < 0.75 else "captured"

            else:  # suspicious_geo_domain
                amount = m_profile["avg_amount"] * np.random.uniform(2.0, 5.5)
                email_domain = random.choice(disposable_domains) if random.random() < 0.65 else random.choice(email_domains)
                billing_country = random.choice(["US", "GB", "AE", "SG"])
                payment_method = "card"
                status = "captured" if random.random() < 0.90 else "failed"

            card_network = random.choice(card_networks) if payment_method == "card" else None
            bank_name = random.choice(banks)

        txn = {
            "transaction_id": f"txn_{txn_counter:06d}",
            "merchant_id": merchant_id,
            "customer_id": customer_id,
            "amount": round(float(amount), 2),
            "currency": "INR",
            "payment_method": payment_method,
            "timestamp": timestamp.isoformat(),
            "transaction_status": status,
            "card_network": card_network,
            "bank_name": bank_name,
            "email_domain": email_domain,
            "billing_country": billing_country,
            "is_fraud": is_fraud,
        }
        transactions.append(txn)
        txn_counter += 1

    df = pd.DataFrame(transactions)
    # Ensure chronological sorting
    df = df.sort_values("timestamp").reset_index(drop=True)

    return df


if __name__ == "__main__":
    output_dir = os.path.join(os.path.dirname(__file__), "raw")
    os.makedirs(output_dir, exist_ok=True)
    raw_path_csv = os.path.join(output_dir, "transactions_raw.csv")
    raw_path_parquet = os.path.join(output_dir, "transactions_raw.parquet")

    print(f"Generating synthetic transaction dataset...")
    df_raw = generate_synthetic_transactions(
        num_merchants=20,
        txns_per_merchant=500,
        fraud_prevalence=0.08,
        random_seed=42,
        time_span_days=30,
    )

    df_raw.to_csv(raw_path_csv, index=False)
    print(f"Saved CSV to: {raw_path_csv}")

    try:
        df_raw.to_parquet(raw_path_parquet, index=False)
        print(f"Saved Parquet to: {raw_path_parquet}")
    except Exception:
        print("Note: Parquet export skipped (pyarrow optional). Using CSV for pipeline.")

    fraud_count = int(df_raw["is_fraud"].sum())
    total = len(df_raw)
    print(f"Dataset generated successfully!")
    print(f"Total Transactions: {total}")
    print(f"Fraud / Anomalous Transactions: {fraud_count} ({fraud_count/total:.2%})")
    print(f"Legitimate Transactions: {total - fraud_count} ({(total - fraud_count)/total:.2%})")
